export function getSkillMeltTemplate(
  materialTag: ForgeMaterialType | '',
  skillType: ForgeSkillType | '',
  genre?: string | null,
): SkillMeltTemplate {
  if (!materialTag || !skillType) return { focus: '', description: '' }
  const selected = skillTemplateMap[materialTag][skillType]
  const genreValue = genre?.trim()
  const currentGenre = genreValue
    ? genreValue.endsWith('题材') ? genreValue : `${genreValue}题材`
    : '当前题材'
  return {
    focus: selected.focus.replaceAll('当前题材', currentGenre),
    description: selected.description.replaceAll('当前题材', currentGenre),
  }
}
